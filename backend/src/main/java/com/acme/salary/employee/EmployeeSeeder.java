package com.acme.salary.employee;

import java.nio.charset.StandardCharsets;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.core.io.ClassPathResource;
import org.springframework.core.io.support.EncodedResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.init.ScriptUtils;
import org.springframework.stereotype.Component;
import org.springframework.transaction.support.TransactionTemplate;

/**
 * Loads the 10,000 demo employees the first time the app starts on an empty database. A freshly deployed server has
 * no database file yet, so it cannot rely on someone running the seed script. Turn on with SEED_EMPLOYEES=true.
 *
 * <p>The data comes from {@code db/seed/employees.sql}, which is generated by {@code scripts/seed-employees.js
 * --emit-sql}, so there is only one data generator to maintain. If employees already exist, nothing happens.
 */
@Component
@ConditionalOnProperty(name = "app.seed.employees", havingValue = "true")
class EmployeeSeeder implements ApplicationRunner {

    private static final Logger log = LoggerFactory.getLogger(EmployeeSeeder.class);

    private final JdbcTemplate jdbc;
    private final TransactionTemplate transaction;

    EmployeeSeeder(JdbcTemplate jdbc, TransactionTemplate transaction) {
        this.jdbc = jdbc;
        this.transaction = transaction;
    }

    @Override
    public void run(ApplicationArguments args) {
        Long existing = jdbc.queryForObject("SELECT COUNT(*) FROM employees", Long.class);
        if (existing != null && existing > 0) {
            log.info("Employees already present ({}), not seeding", existing);
            return;
        }
        long started = System.currentTimeMillis();
        // One transaction: either all 10,000 employees are added or none.
        transaction.executeWithoutResult(status -> jdbc.execute((java.sql.Connection connection) -> {
            ScriptUtils.executeSqlScript(connection,
                    new EncodedResource(new ClassPathResource("db/seed/employees.sql"), StandardCharsets.UTF_8));
            return null;
        }));
        log.info("Seeded {} demo employees in {} ms", jdbc.queryForObject("SELECT COUNT(*) FROM employees", Long.class),
                System.currentTimeMillis() - started);
    }
}
